@dataclass
class Paso:
    id: str
    texto: str
    seccion: str = ""
    pestana: str = ""


@dataclass
class Ficha:
    id: str
    tema: str
    titulo: str
    sintomas: List[str] = field(default_factory=list)
    causas: List[str] = field(default_factory=list)
    pasos: List[Paso] = field(default_factory=list)
    propia: bool = False
    origen: str = ""          # ficha fija de la que se duplicó (si se duplicó)

    def a_dict(self) -> Dict:
        return {"tema": self.tema, "titulo": self.titulo, "sintomas": list(self.sintomas),
                "causas": list(self.causas), "origen": self.origen,
                "pasos": [{"id": p.id, "texto": p.texto, "seccion": p.seccion, "pestana": p.pestana}
                          for p in self.pasos]}


