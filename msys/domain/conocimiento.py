def todas_las_fichas(propias: Optional[List[Ficha]] = None) -> List[Ficha]:
    return list(FICHAS_FIJAS) + list(propias or [])


def _normalizar(texto: str) -> str:
    sin = unicodedata.normalize("NFD", texto.lower())
    return "".join(c for c in sin if unicodedata.category(c) != "Mn")


def coincide(ficha: Ficha, busqueda: str) -> bool:
    """Todas las palabras buscadas aparecen en algún texto de la ficha (sin acentos ni mayúsculas)."""
    palabras = _normalizar(busqueda).split()
    if not palabras:
        return True
    texto = _normalizar(" ".join([ficha.titulo, TITULO_TEMA.get(ficha.tema, ""), *ficha.sintomas,
                                  *ficha.causas, *(f"{p.texto} {p.seccion} {p.pestana}" for p in ficha.pasos)]))
    return all(p in texto for p in palabras)


def duplicar(ficha: Ficha) -> Ficha:
    """Copia editable de una ficha (nuevo id y pasos con ids nuevos)."""
    nid = "u-" + uuid.uuid4().hex[:12]
    return Ficha(nid, ficha.tema, ficha.titulo, list(ficha.sintomas), list(ficha.causas),
                 [Paso(f"{nid}.{i}", p.texto, p.seccion, p.pestana) for i, p in enumerate(ficha.pasos, 1)],
                 propia=True, origen=ficha.id if not ficha.propia else ficha.origen)


def nueva_ficha(tema: str = "red") -> Ficha:
    return Ficha("u-" + uuid.uuid4().hex[:12], tema, "", propia=True)


def nuevo_paso(ficha: Ficha) -> Paso:
    usados = {p.id for p in ficha.pasos}
    i = len(ficha.pasos) + 1
    while f"{ficha.id}.{i}" in usados:
        i += 1
    return Paso(f"{ficha.id}.{i}", "")


class ConocimientoDB:
    """Fichas propias del técnico en multisys.db (misma base que el resto de MASys)."""

    def __init__(self, path: Optional[str] = None):
        self.path = path or os.path.join(msys_config.app_base_dir(), "multisys.db")
        self._init_schema()

    def _conn(self):
        return _sqlite_connect(self.path)

    def _init_schema(self):
        with self._conn() as conn:
            conn.execute("""
                CREATE TABLE IF NOT EXISTS conocimiento_fichas (
                    id TEXT PRIMARY KEY,
                    datos TEXT NOT NULL,
                    creado TEXT NOT NULL,
                    modificado TEXT NOT NULL
                )
            """)

    def listar(self) -> List[Ficha]:
        with self._conn() as conn:
            filas = conn.execute("SELECT id, datos FROM conocimiento_fichas ORDER BY creado").fetchall()
        fichas = []
        for id_, datos in filas:
            try:
                d = json.loads(datos)
                pasos = [Paso(str(p.get("id") or f"{id_}.{i}"), str(p.get("texto", "")),
                              str(p.get("seccion", "")), str(p.get("pestana", "")))
                         for i, p in enumerate(d.get("pasos", []), 1)]
                fichas.append(Ficha(id_, str(d.get("tema", "red")), str(d.get("titulo", "")),
                                    [str(s) for s in d.get("sintomas", [])], [str(c) for c in d.get("causas", [])],
                                    pasos, propia=True, origen=str(d.get("origen", ""))))
            except (ValueError, TypeError, AttributeError):
                continue  # fila dañada: no rompe la ventana
        return fichas

    def guardar(self, ficha: Ficha) -> None:
        if not ficha.propia:
            raise ValueError("Las fichas que vienen con MASys no se modifican: duplícala")
        if not ficha.titulo.strip():
            raise ValueError("La ficha necesita un título")
        ahora = datetime.now().isoformat(timespec="seconds")
        datos = json.dumps(ficha.a_dict(), ensure_ascii=False)
        with self._conn() as conn:
            conn.execute("""INSERT INTO conocimiento_fichas (id, datos, creado, modificado) VALUES (?, ?, ?, ?)
                            ON CONFLICT(id) DO UPDATE SET datos = excluded.datos, modificado = excluded.modificado""",
                         (ficha.id, datos, ahora, ahora))

    def eliminar(self, ficha_id: str) -> None:
        with self._conn() as conn:
            conn.execute("DELETE FROM conocimiento_fichas WHERE id = ?", (ficha_id,))
